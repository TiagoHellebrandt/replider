-- for "UTI II Neonatal" with ten beds is not declaring an intention — it is
-- receiving money against an ordinance and is required to have the equipment
-- that entitles it. Measured over HB/MT on 2026-09-18: 429 rows across 191
-- hospitals, 548 funded beds, 120 of them neonatal. That is a harder buying
-- signal than a declared bed, and the product had never read the file.
--
-- SERVIÇOS ESPECIALIZADOS (SR) are what the establishment says it performs —
-- 26.917 rows across 5.483 establishments in Mato Grosso, the qualifier that
-- separates a hospital that runs a neonatal service from one that has a cot.
--
-- Both dictionaries are SEEDED TABLES taken from the ministry's own TAB_CNES
-- archive (DBF/HABILITA.DBF and DBF/S_CLASSEN.dbf), for the reason the bed
-- dictionary already documents: this audit read the ministry's codes wrong
-- twice from memory before opening the files that define them.

