-- Public data, not account-scoped — same shape as cnes_equipment and
-- cnes_beds.
CREATE TABLE IF NOT EXISTS cnes_habilitations (
    cnes        CHAR(7) NOT NULL,
    code        CHAR(4) NOT NULL,
    competencia CHAR(6) NOT NULL,
    uf          CHAR(2) NOT NULL,
    city_code   TEXT,
    -- Beds the ordinance funds. Zero is common: plenty of habilitations are
    -- not bed-based, and zero must never be read as "no capacity".
    beds        INTEGER NOT NULL DEFAULT 0,
    -- The ministry's validity window, as competencias. valid_to '399999' is
    -- how DATASUS writes open-ended; it is kept verbatim rather than turned
    -- into a date nobody could check against the source.
    valid_from  CHAR(6),
    valid_to    CHAR(6),
    ordinance   TEXT,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (cnes, code, competencia)
);

CREATE INDEX IF NOT EXISTS idx_cnes_hab_uf_comp ON cnes_habilitations(uf, competencia);
CREATE INDEX IF NOT EXISTS idx_cnes_hab_cnes ON cnes_habilitations(cnes);

CREATE TABLE IF NOT EXISTS cnes_services (
    cnes         CHAR(7) NOT NULL,
    service_code CHAR(3) NOT NULL,
    class_code   CHAR(3) NOT NULL,
    competencia  CHAR(6) NOT NULL,
    uf           CHAR(2) NOT NULL,
    city_code    TEXT,
    -- Whether the service is offered to SUS patients. A seller reads it as
    -- which budget pays for it.
    sus          BOOLEAN NOT NULL DEFAULT FALSE,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (cnes, service_code, class_code, competencia)
);

CREATE INDEX IF NOT EXISTS idx_cnes_srv_uf_comp ON cnes_services(uf, competencia);
CREATE INDEX IF NOT EXISTS idx_cnes_srv_cnes ON cnes_services(cnes);
