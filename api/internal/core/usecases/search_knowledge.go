package usecases

import (
	"context"
	"log/slog"
	"sync"
	"sync/atomic"
	"time"

	"github.com/replider/api/internal/core/domain"
)

// defaultMaxRegenPerMin caps how many chunk embeddings the lazy migration
// will regenerate per minute (US-027). A provider switch on a large source
// used to re-embed EVERY chunk inline on the first search — a latency spike
// and a cost spike proportional to the source size. We now migrate only the
// mismatched chunks that actually surface in the result set, and never more
// than this many per minute. The remaining chunks migrate on later searches.
const defaultMaxRegenPerMin = 60

type SearchKnowledgeUseCase struct {
	knowledgeRepo domain.KnowledgeRepository
	aiFactory     domain.AIProvider // We'll use the default provider for embeddings

	// maxRegenPerMin throttles lazy re-embedding so a provider switch can
	// never stampede the embedding provider. 0 falls back to the default.
	maxRegenPerMin int

	// regenTotal is the exported metric: total chunk embeddings regenerated
	// over the process lifetime (the "regen rate" numerator). Monotonic.
	regenTotal atomic.Int64

	mu          sync.Mutex
	windowStart time.Time
	windowCount int
}

func NewSearchKnowledgeUseCase(knowledgeRepo domain.KnowledgeRepository, aiProvider domain.AIProvider) *SearchKnowledgeUseCase {
	return &SearchKnowledgeUseCase{
		knowledgeRepo:  knowledgeRepo,
		aiFactory:      aiProvider,
		maxRegenPerMin: defaultMaxRegenPerMin,
	}
}

// RegenCount returns the total number of chunk embeddings regenerated by the
// lazy migration since process start (US-027 metric). Exposed so a metrics
// endpoint / log can report the regeneration rate.
func (uc *SearchKnowledgeUseCase) RegenCount() int64 {
	return uc.regenTotal.Load()
}

// allowRegen returns true if another lazy regeneration is permitted within
// the current one-minute window, incrementing the window counter when so.
// Throttled regenerations are simply skipped — the chunk keeps its stale
// embedding and migrates on a future search.
func (uc *SearchKnowledgeUseCase) allowRegen(now time.Time) bool {
	limit := uc.maxRegenPerMin
	if limit <= 0 {
		limit = defaultMaxRegenPerMin
	}

	uc.mu.Lock()
	defer uc.mu.Unlock()

	if uc.windowStart.IsZero() || now.Sub(uc.windowStart) >= time.Minute {
		uc.windowStart = now
		uc.windowCount = 0
	}
	if uc.windowCount >= limit {
		return false
	}
	uc.windowCount++
	return true
}

func (uc *SearchKnowledgeUseCase) Execute(ctx context.Context, sourceID, query string, limit int32, currentProvider string) ([]*domain.KnowledgeChunk, error) {
	// 1. Generate embedding for the query
	embedding, err := uc.aiFactory.GetEmbedding(ctx, query)
	if err != nil {
		return nil, err
	}

	// 2. Search in Postgres
	chunks, err := uc.knowledgeRepo.Search(ctx, sourceID, embedding, limit)
	if err != nil {
		return nil, err
	}

	// 3. Lazy, per-chunk re-embedding (US-027).
	// Only the chunks that actually surfaced in this result set and whose
	// stored provider mismatches the current one are regenerated — never the
	// whole source. Each regeneration counts against a per-minute throttle so
	// a provider switch on a large knowledge base degrades gracefully instead
	// of stampeding the embedding provider on a single inbound turn.
	for _, c := range chunks {
		if c.Provider != nil && *c.Provider == currentProvider {
			continue
		}
		if !uc.allowRegen(time.Now()) {
			slog.Warn("knowledge: regen throttled, deferring chunk migration",
				"source_id", sourceID, "chunk_id", c.ID)
			continue
		}
		newEmb, err := uc.aiFactory.GetEmbedding(ctx, c.Content)
		if err != nil {
			slog.Error("knowledge: lazy re-embed failed", "chunk_id", c.ID, "error", err)
			continue
		}
		if err := uc.knowledgeRepo.UpdateEmbedding(ctx, c.ID, newEmb, currentProvider); err != nil {
			slog.Error("knowledge: persist re-embed failed", "chunk_id", c.ID, "error", err)
			continue
		}
		uc.regenTotal.Add(1)
		// Reflect the migration in the returned chunk so callers see the
		// fresh provider/embedding without a re-search.
		p := currentProvider
		c.Provider = &p
		c.Embedding = newEmb
	}

	// 4. Trimming context (max 2000 characters ≈ 500-800 tokens)
	var finalChunks []*domain.KnowledgeChunk
	totalLen := 0
	for _, c := range chunks {
		if totalLen+len(c.Content) > 2000 {
			break
		}
		finalChunks = append(finalChunks, c)
		totalLen += len(c.Content)
	}

	return finalChunks, nil
}
