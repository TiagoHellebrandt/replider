package usecases

import (
	"context"
	"errors"
	"fmt"
	"strings"
	"time"

	"github.com/oklog/ulid/v2"
	"github.com/replider/api/internal/core/domain"
	"github.com/replider/api/internal/core/services"
)

// suggestionSuffix is appended to every preview-chat system prompt so
// the model generates context-aware follow-up suggestions that the UI
// renders as clickable chips. The format is parseable and stripped from
// the displayed response before reaching the client.
const suggestionSuffix = `

Ao final de cada resposta, sugira 3 perguntas educadas e relevantes que o cliente poderia fazer em seguida. Use exatamente este formato:
[SUGESTOES]Pergunta 1?|Pergunta 2?|Pergunta 3?[/SUGESTOES]
Nunca inclua perguntas ofensivas, grosseiras ou negativas — mantenha um tom acolhedor e profissional.`

// PreviewChatDTO defines the input for the use case.
type PreviewChatDTO struct {
	AccountID string `json:"account_id"`
	AgentID   string `json:"agent_id"`
	Message   string `json:"message"`
}

// PreviewChatResponse defines the output for the use case.
type PreviewChatResponse struct {
	Response     string `json:"response"`
	TokensUsed   int64  `json:"tokens_used"`
	TokensRemain int64  `json:"tokens_remain"`
	// Suggestions carries 3 polite follow-up questions generated by
	// the AI at the end of each turn. The frontend renders them as
	// clickable chips; tapping one pre-fills the input and the next
	// turn gets new context-aware suggestions. Empty when the model
	// didn't produce the expected [SUGESTOES] block (fallback to the
	// template's static set happens client-side).
	Suggestions []string `json:"suggestions,omitempty"`
	// Handoff is true when the agent decided to pass the conversation to
	// a person. In a real conversation the pipeline reacts by pausing the
	// bot; in the preview there is nobody to hand off TO, so the flag
	// exists to let the client explain what would have happened instead of
	// rendering the control token.
	Handoff bool `json:"handoff,omitempty"`
}

type PreviewChatUseCase struct {
	accountRepo  domain.AccountRepository
	agentRepo    domain.AgentRepository
	usageRepo    domain.UsageRepository
	planRepo     domain.PlanRepository
	auditLogRepo domain.AuditLogRepository
	aiFactory    domain.AIFactory
	agentRunner  *services.AgentRunner
	usageGuard   services.UsageChecker
}

// SetUsageGuard injects the usage guard for token limit enforcement.
func (uc *PreviewChatUseCase) SetUsageGuard(g services.UsageChecker) {
	uc.usageGuard = g
}

func NewPreviewChatUseCase(
	accountRepo domain.AccountRepository,
	agentRepo domain.AgentRepository,
	usageRepo domain.UsageRepository,
	planRepo domain.PlanRepository,
	auditLogRepo domain.AuditLogRepository,
	aiFactory domain.AIFactory,
	agentRunner *services.AgentRunner,
) *PreviewChatUseCase {
	return &PreviewChatUseCase{
		accountRepo:  accountRepo,
		agentRepo:    agentRepo,
		usageRepo:    usageRepo,
		planRepo:     planRepo,
		auditLogRepo: auditLogRepo,
		aiFactory:    aiFactory,
		agentRunner:  agentRunner,
	}
}

func (uc *PreviewChatUseCase) Execute(ctx context.Context, dto PreviewChatDTO) (*PreviewChatResponse, error) {
	// 1. Fetch Agent and verify ownership
	agent, err := uc.agentRepo.GetByID(ctx, dto.AgentID)
	if err != nil || agent == nil {
		return nil, domain.ErrAgentNotFound
	}
	if agent.AccountID != dto.AccountID {
		return nil, domain.ErrAgentNotFound
	}

	// 2. Fetch Account
	account, err := uc.accountRepo.GetByID(ctx, dto.AccountID)
	if err != nil || account == nil {
		return nil, domain.ErrAccountNotFound
	}

	// 3. Fetch Plan (fallback to Trial)
	var plan *domain.Plan
	if account.PlanID == nil {
		plan = domain.TrialPlan()
	} else {
		plan, err = uc.planRepo.GetByID(ctx, *account.PlanID)
		if err != nil || plan == nil {
			plan = domain.TrialPlan()
		}
	}

	// 4. Fetch Usage and check limits
	usage, _ := uc.usageRepo.GetByAccountID(ctx, dto.AccountID)
	if usage != nil && uc.usageGuard != nil {
		if err := uc.usageGuard.Check(account, plan, usage, "tokens"); err != nil {
			return nil, err
		}
	}
	var currentTokens int64
	if usage != nil && usage.AITokensUsed != nil {
		currentTokens = *usage.AITokensUsed
	}
	addonTokens := int64(0)
	if usage != nil && usage.AddonTokens != nil {
		addonTokens = *usage.AddonTokens
	}
	// EffectiveMax, not the raw column: a contract plan stores 0 and
	// relies on the account's override, so reading the raw value would
	// hard-block AI for exactly the customers paying the most.
	effectiveLimit := account.EffectiveMaxAITokensPerMonth(plan) + addonTokens

	// 6. Build the system prompt using the AgentRunner (single source of truth for prompt logic).
	// Same language detection as the live path so preview matches prod
	// behavior exactly.
	replyLanguage := services.DetectReplyLanguage(dto.Message)
	promptResult, err := uc.agentRunner.BuildSystemPrompt(ctx, agent, dto.Message, account.Name, replyLanguage)
	if err != nil {
		return nil, fmt.Errorf("failed to build system prompt: %w", err)
	}

	// 7. Get AI provider and generate response. Wrap both failures in a
	// typed AppError (AI_PROVIDER_UNAVAILABLE) so the handler maps them
	// to a proper 502 with a readable code instead of a generic 500.
	// The underlying error (model_not_found, bad API key, upstream
	// outage, ...) still rides along in the message for ops.
	// Account-scoped, not the platform key: with AI_REQUIRE_BYOK a keyless
	// account gets BYOK_KEY_MISSING here (the "configure sua chave" banner)
	// instead of previewing on the platform's bill.
	aiPrv, err := uc.aiFactory.GetProviderForAccount(ctx, plan.AIProvider, account, plan)
	if errors.Is(err, domain.ErrBYOKKeyMissing) {
		return nil, domain.ErrBYOKKeyMissing
	}
	if err != nil {
		return nil, &domain.AppError{
			Code:    domain.ErrAIProviderUnavailable.Code,
			Message: fmt.Sprintf("failed to initialize AI provider: %v", err),
		}
	}

	history := []domain.ChatMessage{
		{Role: "user", Content: dto.Message},
	}

	// Append suggestion instruction so the model generates context-aware
	// follow-up chips at the end of every turn. The block is parsed and
	// stripped before reaching the client (see parseSuggestions below).
	enrichedPrompt := promptResult.SystemPrompt + suggestionSuffix

	resp, err := aiPrv.GenerateResponse(ctx, enrichedPrompt, history, promptResult.Tools)
	if err != nil {
		return nil, &domain.AppError{
			Code:    domain.ErrAIProviderUnavailable.Code,
			Message: fmt.Sprintf("AI provider failed to generate response: %v", err),
		}
	}
	// Defensive nil guard. An SDK that returned (nil, nil) would panic
	// further down at parseSuggestions(resp.Content); convert it to a
	// typed error the handler can log + surface as 502 instead.
	if resp == nil {
		return nil, &domain.AppError{
			Code:    domain.ErrAIProviderUnavailable.Code,
			Message: "AI provider returned an empty response",
		}
	}

	// 8. Calculate token cost
	var promptTokens, completionTokens int64
	if resp != nil {
		promptTokens = resp.Usage.PromptTokens
		completionTokens = resp.Usage.CompletionTokens
	}
	tokensCost := int64((float64(promptTokens) * plan.InputMultiplier) + (float64(completionTokens) * plan.OutputMultiplier))
	if tokensCost == 0 {
		tokensCost = 100 // fallback
	}
	newTotalTokens := currentTokens + tokensCost

	// 9. Increment usage
	if usage != nil {
		usage.AITokensUsed = &newTotalTokens
		usage.UpdatedAt = time.Now().UTC()
		_ = uc.usageRepo.Update(ctx, usage)
	}

	// 10. Audit log
	_ = uc.auditLogRepo.Create(ctx, &domain.AuditLog{
		ID:         ulid.Make().String(),
		AccountID:  dto.AccountID,
		Action:     "agent.preview_chat",
		EntityType: "agent",
		EntityID:   dto.AgentID,
		CreatedAt:  time.Now().UTC(),
	})

	tokensRemain := effectiveLimit - newTotalTokens
	if tokensRemain < 0 {
		tokensRemain = 0
	}

	// Mark the onboarding milestone (idempotent at the SQL level — only
	// flips the flag the first time). Best-effort: never fail the chat
	// turn because the side-effect failed; the dashboard checklist will
	// still derive AgentCreated from EXISTS so progress isn't lost.
	_ = uc.accountRepo.MarkPreviewChatTested(ctx, dto.AccountID)

	cleanResponse, suggestions := parseSuggestions(resp.Content)

	// The model answers a hand-off by emitting a control token, and the real
	// pipeline consumes it (inbound_webhook.go) to pause the bot. The preview
	// had no such step, so the token reached the screen verbatim: somebody
	// evaluating the product typed a question and got "[HANDOFF]" back, on the
	// one screen built to show the agent working.
	handoff := strings.Contains(cleanResponse, services.HandoffSentinel)
	if handoff {
		cleanResponse = strings.TrimSpace(
			strings.ReplaceAll(cleanResponse, services.HandoffSentinel, ""))
	}

	return &PreviewChatResponse{
		Response:     cleanResponse,
		TokensUsed:   tokensCost,
		TokensRemain: tokensRemain,
		Suggestions:  suggestions,
		Handoff:      handoff,
	}, nil
}

// parseSuggestions extracts the [SUGESTOES]...[/SUGESTOES] block from
// the AI response and returns the cleaned response + up to 3 follow-up
// questions. If the model didn't produce the expected format, the
// response text is returned as-is with an empty slice — the client
// falls back to the template's static suggestions in that case.
func parseSuggestions(raw string) (string, []string) {
	const open = "[SUGESTOES]"
	const close = "[/SUGESTOES]"

	startIdx := strings.Index(raw, open)
	endIdx := strings.Index(raw, close)
	if startIdx < 0 || endIdx < 0 || endIdx <= startIdx {
		return strings.TrimSpace(raw), nil
	}

	block := raw[startIdx+len(open) : endIdx]
	cleaned := strings.TrimSpace(raw[:startIdx] + raw[endIdx+len(close):])

	parts := strings.Split(block, "|")
	var suggestions []string
	for _, p := range parts {
		s := strings.TrimSpace(p)
		if s != "" && len(suggestions) < 3 {
			suggestions = append(suggestions, s)
		}
	}
	return cleaned, suggestions
}
