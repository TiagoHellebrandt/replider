// runWhatsAppTokenHealthCheck iterates active WhatsApp channels and
// probes the Graph API with the stored access_token. Failures are
// logged with channel_id + waba_id + phone_number_id so an ops
// dashboard can alert on revoked/expired tokens. We deliberately do
// NOT mutate channel state here — the next user action already
// surfaces TOKEN_EXPIRED via mapMetaError and shows the reconnect
// CTA; this job exists purely for visibility.
func runWhatsAppTokenHealthCheck(ctx context.Context, repo domain.ChannelRepository) {
	channels, err := repo.ListAllByProvider(ctx, "whatsapp")
	if err != nil {
		slog.Error("token health: failed to list WhatsApp channels", "error", err)
		return
	}
	var checked, unhealthy int
	for _, ch := range channels {
		if !ch.IsActive {
			continue
		}
		var cfg struct {
			PhoneNumberID string `json:"phone_number_id"`
			WABAID        string `json:"waba_id"`
			AccessToken   string `json:"access_token"`
		}
		if err := json.Unmarshal(channelConfigBytes(ch.Config), &cfg); err != nil ||
			cfg.PhoneNumberID == "" || cfg.AccessToken == "" {
			continue
		}
		checked++
		probeCtx, cancel := context.WithTimeout(ctx, 10*time.Second)
		_, err := whatsapp.GetPhoneNumberDetails(probeCtx, cfg.PhoneNumberID, cfg.AccessToken)
		cancel()
		if err != nil {
			unhealthy++
			slog.Warn("token health: WhatsApp channel unhealthy",
				"channel_id", ch.ID,
				"account_id", ch.AccountID,
				"phone_number_id", cfg.PhoneNumberID,
				"waba_id", cfg.WABAID,
				"error", err.Error())
		}
	}
	slog.Info("token health: WhatsApp sweep complete",
		"checked", checked,
		"unhealthy", unhealthy)
}

// detectNgrokURL queries the ngrok local API (running inside the same container)
// to discover the active HTTPS tunnel URL. Retries for up to 15s to handle
// cases where ngrok starts slightly after the Go process.
func detectNgrokURL() string {
	return detectNgrokURLFrom("http://localhost:4040/api/tunnels", 10, 1500*time.Millisecond)
}

// detectNgrokURLFrom queries the given ngrok tunnels API endpoint up to maxRetries
// times, sleeping retryInterval between attempts, and returns the first HTTPS
// tunnel URL found. Returns "" if none is found after all retries.
func detectNgrokURLFrom(tunnelsURL string, maxRetries int, retryInterval time.Duration) string {
	client := &http.Client{Timeout: 2 * time.Second}
	for i := 0; i < maxRetries; i++ {
		resp, err := client.Get(tunnelsURL)
		if err == nil {
			var result struct {
				Tunnels []struct {
					PublicURL string `json:"public_url"`
				} `json:"tunnels"`
			}
			if json.NewDecoder(resp.Body).Decode(&result) == nil {
				resp.Body.Close()
				for _, t := range result.Tunnels {
					if strings.HasPrefix(t.PublicURL, "https://") {
						return t.PublicURL
					}
				}
			} else {
				resp.Body.Close()
			}
		}
		time.Sleep(retryInterval)
	}
	return ""
}

// waPhoneProber adapts whatsapp.GetPhoneNumberStatus to the
// services.WAPhoneProber port consumed by the WhatsAppQualityWorker.
// Falls back to the app/system access token when a channel has no token
// of its own (BSP-managed numbers).
type waPhoneProber struct{ appToken string }

func (p *waPhoneProber) PhoneStatus(ctx context.Context, phoneNumberID, accessToken string) (string, string, error) {
	token := accessToken
	if token == "" {
		token = p.appToken
	}
	s, err := whatsapp.GetPhoneNumberStatus(ctx, phoneNumberID, token)
	if err != nil {
		return "", "", err
	}
	return s.QualityRating, s.MessagingLimitTier, nil
}

// autoHuntAdapter carries the nightly hunt's result across the layer
// boundary: services must not import usecases, so the summary is restated
// rather than shared.
type autoHuntAdapter struct{ uc *usecases.AutoHuntUseCase }

func (a autoHuntAdapter) Run(ctx context.Context) []services.AutoHuntSummary {
	res := a.uc.Run(ctx)
	out := make([]services.AutoHuntSummary, 0, len(res))
	for _, r := range res {
		out = append(out, services.AutoHuntSummary{
			AccountID: r.AccountID, Found: r.Found, Created: r.Created,
		})
	}
	return out
}
