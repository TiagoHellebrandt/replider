	//
	// appCtx is the parent context for every long-lived background
	// worker (ingestion, CSAT asker, WhatsApp outbox drain, campaign
	// runner, token health check, etc.). It cancels on SIGTERM/SIGINT
	// before srv.Shutdown so workers stop pulling new jobs while the
	// HTTP server drains in-flight requests. Previously each worker was
	// passed context.Background() and kept running through the 10-second
	// drain window — claiming new jobs that crashed half-finished when
	// the container actually exited.
	appCtx, appCancel := context.WithCancel(context.Background())
	defer appCancel()
	ctx := appCtx

	// Parse the pool config once so we can attach the OpenTelemetry query
	// tracer (US-066). otelpgx emits a span per DB query off the global
	// TracerProvider — a no-op when tracing is disabled, so it's free in
