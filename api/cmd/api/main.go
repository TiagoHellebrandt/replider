	// loopback, RFC1918 or the cloud metadata endpoint.
	httpsafe.SetAllowPrivateTargets(cfg.AllowPrivateWebhookTargets)

	// Observability: Sentry init BEFORE anything that could panic, and
	// flush on shutdown so in-flight events actually ship.
	sentryFlush := observability.InitSentry(cfg.SentryDSN, cfg.Environment, os.Getenv("RELEASE_SHA"))
	defer sentryFlush()

	// Observability: OpenTelemetry distributed tracing (US-066). No-op when
	// OTEL_EXPORTER_OTLP_ENDPOINT is unset (local dev, tests). Sets the
	// global TracerProvider that otelgin (HTTP), otelpgx (DB) and the AI
	// tracingProvider (LLM) all draw from. Shutdown flushes buffered spans.
	tracingShutdown, tErr := observability.InitTracing(
		context.Background(),
		cfg.OTelExporterEndpoint,
		cfg.OTelServiceName,
		cfg.Environment,
		os.Getenv("RELEASE_SHA"),
	)
	if tErr != nil {
		slog.Error("failed to initialize tracing", "error", tErr)
		os.Exit(1)
	}
	defer func() {
		shutdownCtx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
		defer cancel()
		if err := tracingShutdown(shutdownCtx); err != nil {
			slog.Error("tracing shutdown error", "error", err)
		}
	}()

