	// replies, takeover sends) are mirrored to the CUSTOMER account's
	// WebSocket clients so the support widget updates live. The platform
	// side keeps the normal new_message broadcast its callers already do.
	inappAdapter.SetBroadcaster(wsHub, convRepo)

	// US-196: cross-pod WebSocket fanout via Redis pub/sub. With more than one
	// API pod behind the LB, a broadcast produced on the pod that handled an
	// inbound webhook must still reach a dashboard socket on another pod. When
	// Redis is unreachable the hub stays single-pod (publisher nil → local
	// delivery only), matching the cache fallback contract. See docs/ws-scaling.md.
