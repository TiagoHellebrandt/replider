	// Concrete-pointer guard before the interface assignment — a typed nil
	// inside an interface is non-nil, and would defeat every "not configured"
	// check downstream (same trap as TurnstileVerifier and gcalOAuth above).
	var googleMailPort usecases.GoogleMailConnector
