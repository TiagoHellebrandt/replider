	// Level is LOG_LEVEL-driven, defaulting to info so prod stays quiet
	// (US-029); set LOG_LEVEL=debug to surface verbose diagnostics on
	// demand without a redeploy.
	// ReplaceAttr redacts PII (phone, email, cpf) from every log record so
	// personal data never lands in stdout/Docker logs (US-050, LGPD). See
	// docs/logging.md and observability.RedactPII.
	// MeteringHandler wraps the JSON handler to count every emitted record
	// into the log_lines_total{level} Prometheus series (US-075) so the
	// HighLogVolume alert can catch a runaway log bill; it is otherwise
	// transparent (redaction + formatting stay with the JSON handler).
	jsonHandler := slog.NewJSONHandler(os.Stdout, &slog.HandlerOptions{
		Level:       parseLogLevel(os.Getenv("LOG_LEVEL")),
		ReplaceAttr: observability.RedactPII,
	})
	// RecordingHandler guarda uma cópia de WARN e acima numa tabela, para dar
	// para investigar produção sem entrar na máquina (o stdout do contêiner
	// rola para fora de um arquivo de 10MB, e é sempre a linha que interessa
	// que já saiu). Ele nasce desligado do banco: o pool ainda não existe, e
	// as linhas ficam no buffer até o escritor começar.
	logRecorder := observability.NewRecordingHandler(
		observability.NewMeteringHandler(jsonHandler), slog.LevelWarn, 2048)
	logger := slog.New(logRecorder)
	slog.SetDefault(logger)

	// Load Configuration
	cfg := config.Load()
	dbURL := cfg.DBString()

	// SSRF policy for customer-supplied webhook URLs (US-F011). Dev points
