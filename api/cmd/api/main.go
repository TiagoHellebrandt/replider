	var dbPool *pgxpool.Pool
	maxRetries := 10
	for i := 0; i < maxRetries; i++ {
		dbPool, err = pgxpool.NewWithConfig(ctx, poolConfig)
		if err == nil {
			err = dbPool.Ping(ctx)
			if err == nil {
				break
			}
		}

		slog.Info("waiting for database connection", "attempt", i+1, "max_retries", maxRetries)
		time.Sleep(2 * time.Second)
	}

	if err != nil {
		slog.Error("unable to connect to database", "retries", maxRetries, "error", err)
		os.Exit(1)
	}
